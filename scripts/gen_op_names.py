"""Regenerate panoptes_import/op_names.py from OpenProject's own seed files (config/locales/crowdin/<lang>.seeders.yml).

Usage:  python scripts/gen_op_names.py DIR [lang ...] > panoptes_import/op_names.py
DIR holds <lang>.yml copies of the seed files; 'en' can be a copy of an untranslated locale such as rw.seeders.yml
(untranslated locales fall back to the English names). Needs PyYAML. All languages must list the same items in the same order."""
import json
import sys
from pathlib import Path

import yaml

src = Path(sys.argv[1])
langs = sys.argv[2:] or ["en", "nl", "de", "fr", "es", "it", "pt-BR"]
names = {}
for lang in langs:
    seeds = next(iter(yaml.safe_load((src / f"{lang}.yml").read_text(encoding="utf-8")).values()))["seeds"]
    std, common = seeds["standard"], seeds["common"]
    names[lang] = {k: [std[k][f"item_{i}"]["name"] for i in range(len(std[k]))] for k in ("types", "statuses", "priorities")}
    names[lang]["roles"] = [common["project_roles"][f"item_{i}"]["name"] for i in range(len(common["project_roles"]))]
if len({json.dumps({k: len(v) for k, v in n.items()}) for n in names.values()}) != 1:
    sys.exit("item counts differ between languages")
print('"""Names of OpenProject\'s standard work package types, statuses, priorities and project roles per UI language.\n'
      'GENERATED by scripts/gen_op_names.py from OpenProject 17 seed files; do not edit by hand.\n'
      'Items are in the same order in every language, so index i is the same thing everywhere."""\n')
print("LANGUAGES =", json.dumps(langs))
print("NAMES = " + json.dumps(names, ensure_ascii=False, indent=1).replace("true", "True"))
print('''

def candidates(kind: str, english: str) -> list[str]:
    """All names an OpenProject install could use for the standard item whose English name is `english`
    (kind: 'types', 'statuses', 'priorities' or 'roles'), English first, duplicates removed."""
    index = NAMES["en"][kind].index(english)
    out: list[str] = []
    for lang in LANGUAGES:
        name = NAMES[lang][kind][index]
        if name not in out:
            out.append(name)
    return out''')
